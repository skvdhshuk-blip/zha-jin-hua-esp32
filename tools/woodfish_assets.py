#!/usr/bin/env python3
"""Convert the wooden-fish source art and sounds into LVGL/PCM C arrays.

Requires ffmpeg on PATH (or --ffmpeg). The generated files are committed so a
firmware build does not need ffmpeg, but this script keeps the conversion
reproducible:

  python3 tools/woodfish_assets.py

Sources:
  assets/images/woodfish-source.png  1024x1024 RGBA
  assets/images/mallet-source.png    1024x1024 RGBA
  assets/music/woodfish-bell.mp3
Outputs:
  main/assets/woodfish_images.c
  main/assets/woodfish_pcm.c

The knock is synthesized because the AI sound-effect takes were delivered at
roughly -40 dBFS with a noise-like body; peak-normalizing them only amplified
hiss. The bell take is genuine AI audio and is peak-normalized here.
"""

from __future__ import annotations

import argparse
import math
import random
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

FISH_SIZE = 200
MALLET_SIZE = 90
SAMPLE_RATE = 16000
KNOCK_PEAK = 0.90
BELL_PEAK = 0.85


def synth_knock() -> list[int]:
    """A dry wooden-fish strike: mallet click plus damped wood resonances."""
    sr = SAMPLE_RATE
    duration = 0.32
    n = int(sr * duration)
    rng = random.Random(7)
    modes = (
        (240.0, 0.50, 0.075),
        (430.0, 1.00, 0.055),
        (760.0, 0.62, 0.040),
        (1180.0, 0.36, 0.028),
        (1690.0, 0.22, 0.018),
    )
    lowpass = 0.0
    previous = 0.0
    out: list[float] = []
    for i in range(n):
        t = i / sr
        noise = rng.uniform(-1.0, 1.0)
        lowpass += 0.45 * (noise - lowpass)
        click = (lowpass - previous) * math.exp(-t / 0.0022)
        previous = lowpass
        body = sum(a * math.sin(2.0 * math.pi * f * t) * math.exp(-t / d)
                   for f, a, d in modes)
        out.append(0.55 * body + 0.90 * click)
    peak = max(abs(x) for x in out) or 1.0
    scale = KNOCK_PEAK / peak
    samples = [int(max(-1.0, min(1.0, x * scale)) * 32767) for x in out]
    fade = int(0.025 * sr)
    for i in range(fade):
        samples[-fade + i] = int(samples[-fade + i] * (fade - i) / fade)
    return samples


def normalize(samples: list[int], peak: float) -> list[int]:
    top = max(abs(s) for s in samples) or 1
    target = 32767.0 * peak
    scale = target / top
    return [int(max(-32768, min(32767, s * scale))) for s in samples]



def run(cmd: list[str]) -> bytes:
    return subprocess.run(cmd, check=True, stdout=subprocess.PIPE).stdout


def image_c(name: str, symbol: str, source: Path, size: int, flip: bool) -> str:
    vf = f"scale={size}:{size}:flags=lanczos,format=rgba"
    if flip:
        vf = "hflip," + vf
    raw = run([FFMPEG, "-v", "error", "-i", str(source), "-vf", vf,
               "-f", "rawvideo", "-pix_fmt", "rgba", "-"])
    if len(raw) != size * size * 4:
        raise SystemExit(f"{source}: expected {size * size * 4} bytes, got {len(raw)}")

    rgb = bytearray(size * size * 2)
    alpha = bytearray(size * size)
    for i in range(size * size):
        r, g, b, a = raw[i * 4:i * 4 + 4]
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb[i * 2] = value & 0xFF
        rgb[i * 2 + 1] = (value >> 8) & 0xFF
        alpha[i] = a

    data = rgb + alpha
    lines = [
        f"// Generated by tools/woodfish_assets.py from {source.relative_to(ROOT)}.",
        "// Do not edit by hand.",
        '#include "lvgl.h"',
        "",
        f"static const uint8_t {name}_map[] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += [
        "};",
        "",
        f"_Static_assert(sizeof({name}_map) == {size} * {size} * 3,",
        '               "RGB565A8 map size mismatch");',
        "",
        f"const lv_image_dsc_t {symbol} = {{",
        "    .header = {",
        "        .magic = LV_IMAGE_HEADER_MAGIC,",
        "        .cf = LV_COLOR_FORMAT_RGB565A8,",
        "        .flags = 0,",
        f"        .w = {size},",
        f"        .h = {size},",
        f"        .stride = {size * 2},",
        "    },",
        f"    .data_size = sizeof({name}_map),",
        f"    .data = {name}_map,",
        "};",
        "",
    ]
    return "\n".join(lines)


def load_pcm(source: Path, start: float, length: float, fade_start: float,
             fade_len: float, peak: float) -> list[int]:
    filt = (f"afade=t=in:st=0:d=0.003,"
            f"afade=t=out:st={fade_start}:d={fade_len}")
    raw = run([FFMPEG, "-v", "error", "-ss", str(start), "-t", str(length),
               "-i", str(source), "-af", filt, "-ac", "1", "-ar", str(SAMPLE_RATE),
               "-f", "s16le", "-acodec", "pcm_s16le", "-"])
    samples = [int.from_bytes(raw[i:i + 2], "little", signed=True)
               for i in range(0, len(raw) - 1, 2)]
    if not samples:
        raise SystemExit(f"{source}: decoded no audio")
    return normalize(samples, peak)


def pcm_array(name: str, count: str, samples: list[int]) -> str:
    lines = [f"const int16_t {name}[] = {{"]
    for i in range(0, len(samples), 12):
        lines.append("    " + ", ".join(str(s) for s in samples[i:i + 12]) + ",")
    lines += [
        "};",
        f"const size_t {count} = sizeof({name}) / sizeof({name}[0]);",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    global FFMPEG
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", default="ffmpeg")
    args = parser.parse_args()
    FFMPEG = args.ffmpeg

    images = [
        image_c("fish", "woodfish_fish_img",
                ROOT / "assets/images/woodfish-source.png", FISH_SIZE, False),
        image_c("mallet", "woodfish_mallet_img",
                ROOT / "assets/images/mallet-source.png", MALLET_SIZE, True),
    ]
    out = ROOT / "main/assets/woodfish_images.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(images), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")

    knock = synth_knock()
    bell = load_pcm(ROOT / "assets/music/woodfish-bell.mp3",
                    start=0.01, length=2.30, fade_start=2.00, fade_len=0.30,
                    peak=BELL_PEAK)

    pcm = [
        "// Generated by tools/woodfish_assets.py. Knock is synthesized;",
        "// bell is AI audio. 16 kHz, 16-bit mono PCM. Do not edit by hand.",
        '#include "woodfish_audio_assets.h"',
        "",
        pcm_array("woodfish_knock_pcm", "woodfish_knock_samples", knock),
        pcm_array("woodfish_bell_pcm", "woodfish_bell_samples", bell),
    ]
    out = ROOT / "main/assets/woodfish_pcm.c"
    out.write_text("\n".join(pcm), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} "
          f"(knock {len(knock)} samples, bell {len(bell)} samples)")
    return 0


FFMPEG = "ffmpeg"

if __name__ == "__main__":
    raise SystemExit(main())
